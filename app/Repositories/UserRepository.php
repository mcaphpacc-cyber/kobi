<?php

declare(strict_types=1);

namespace App\Repositories;

class UserRepository extends BaseRepository
{
    /**
     * Find a user by email address.
     */
    public function findByEmail(
        string $email
    ): ?array {
        $sql = "
            SELECT
                id,
                name,
                email,
                password_hash,
                status,
                email_verified_at,
                last_login_at,
                created_at,
                updated_at
            FROM users
            WHERE email = :email
            LIMIT 1
        ";

        return $this->fetch(
            $sql,
            [
                'email' => strtolower(trim($email))
            ]
        );
    }

    /**
     * Find a user by ID.
     */
    public function findById(
        int $id
    ): ?array {
        $sql = "
            SELECT
                id,
                name,
                email,
                mobile_number,
                status,
                email_verified_at,
                last_login_at,
                created_at,
                updated_at
            FROM users
            WHERE id = :id
            LIMIT 1
        ";

        return $this->fetch(
            $sql,
            [
                'id' => $id
            ]
        );
    }

    /**
     * Create a new user.
     *
     * The password must already be hashed before
     * reaching the repository.
     */
    public function create(
        string $name,
        string $email,
        string $passwordHash
    ): int {
        $sql = "
            INSERT INTO users (
                name,
                email,
                password_hash,
                password_set_at
            )
            VALUES (
                :name,
                :email,
                :password_hash,
                CURRENT_TIMESTAMP
            )
        ";

        $this->query(
            $sql,
            [
                'name' => trim($name),
                'email' => strtolower(trim($email)),
                'password_hash' => $passwordHash
            ]
        );

        return (int) $this->lastInsertId();
    }

    /**
     * Create a new user from a verified external identity.
     *
     * The password hash is intentionally generated by the
     * service layer and may represent an unusable random
     * password for social-login-only accounts.
     */
    public function createVerified(
        string $name,
        string $email,
        string $passwordHash
    ): int {
        $sql = "
            INSERT INTO users (
                name,
                email,
                password_hash,
                email_verified_at
            )
            VALUES (
                :name,
                :email,
                :password_hash,
                CURRENT_TIMESTAMP
            )
        ";

        $this->query(
            $sql,
            [
                'name' => trim($name),
                'email' => strtolower(trim($email)),
                'password_hash' => $passwordHash
            ]
        );

        return (int) $this->lastInsertId();
    }

    /**
     * Update the user's last login timestamp.
     */
    public function updateLastLogin(
        int $userId
    ): bool {
        return $this->execute(
            "
            UPDATE users
            SET last_login_at = CURRENT_TIMESTAMP
            WHERE id = :id
            ",
            [
                'id' => $userId
            ]
        );
    }

    /**
     * Mark a user's email address as verified.
     */
    public function markEmailVerified(
        int $userId
    ): bool {
        return $this->execute(
            "
            UPDATE users
            SET email_verified_at = CURRENT_TIMESTAMP
            WHERE id = :id
            AND email_verified_at IS NULL
            ",
            [
                'id' => $userId
            ]
        );
    }

    /**
     * Update the user's profile information.
     *
     * When the email address changes, its verification state
     * is reset so the new address must be verified.
     */
    public function updateProfile(
        int $userId,
        string $name,
        string $email,
        bool $emailChanged = false
    ): bool {
        return $this->execute(
            "
            UPDATE users
            SET
                name = :name,
                email = :email,
                email_verified_at =
                    CASE
                        WHEN :email_changed = 1
                        THEN NULL
                        ELSE email_verified_at
                    END
            WHERE id = :id
            ",
            [
                'id' => $userId,
                'name' => trim($name),
                'email' => strtolower(trim($email)),
                'email_changed' => $emailChanged ? 1 : 0
            ]
        );
    }

    public function updateMobileNumber(int $userId, ?string $mobileNumber): void
    {
        // A repeated save of the same value is successful, even with rowCount=0.
        $this->query('UPDATE users SET mobile_number=:mobile WHERE id=:id AND status=\'active\'',
            ['mobile'=>$mobileNumber,'id'=>$userId]);
    }

    /**
     * Update the user's password hash.
     */
    public function updatePassword(
        int $userId,
        string $passwordHash
    ): bool {
        return $this->execute(
            "
            UPDATE users
            SET
                password_hash = :password_hash,
                password_set_at = CURRENT_TIMESTAMP
            WHERE id = :id
            ",
            [
                'id' => $userId,
                'password_hash' => $passwordHash
            ]
        );
    }

    public function hasPassword(
        int $userId
    ): bool {
        $row = $this->fetch(
            "
            SELECT password_set_at
            FROM users
            WHERE id = :id
            LIMIT 1
            ",
            [
                'id' => $userId
            ]
        );

        return
            $row !== null &&
            !empty($row['password_set_at']);
    }
}
